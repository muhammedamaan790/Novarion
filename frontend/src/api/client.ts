// Typed API client. Types are generated from contracts/openapi.json (npm run gen:api); never hand-written.
import type { components } from "./types";

export type Schemas = components["schemas"];
export type TargetId = "cad" | "lad" | "lcx" | "rca";
export const TARGET_IDS: readonly TargetId[] = ["cad", "lad", "lcx", "rca"];
export const VESSELS: readonly TargetId[] = ["lad", "lcx", "rca"];

export type Meta = Schemas["MetaResponse"];
export type PatientBundle = Schemas["PatientBundle"];
export type TargetPrediction = Schemas["TargetPrediction"];
export type ExplanationPayload = Schemas["ExplanationPayload"];
export type EvidencePayload = Schemas["EvidencePayload"];
export type Contribution = Schemas["Contribution"];
export type ErrorResponse = Schemas["ErrorResponse"];

export type PredictionResponse = Schemas["PredictionResponse"];
export type ValidateResponse = Schemas["ValidateResponse"];
export type InputValue = number | string | null;

/** What the 3D view and panels render: a complete, committed analysis. Dataset (OOF) bundles carry all four
 * explanations; a transient /predict analysis carries none, and the Why panel fetches them pinned on demand. */
export type DisplayAnalysis = Pick<
  PatientBundle,
  "analysis_id" | "model_version" | "input_sha256" | "patient" | "quality" | "targets" | "artifact_manifest_sha256"
> & {
  explanations: Partial<Record<TargetId, ExplanationPayload>>;
  evidence: Partial<Record<TargetId, EvidencePayload>>;
  requestInputs?: Record<string, InputValue>; // the exact inputs sent to /predict (needed to pin /explain)
};

export class ApiError extends Error {
  constructor(
    readonly status: number,
    readonly body: ErrorResponse | null,
  ) {
    super(body?.message ?? `HTTP ${status}`);
  }
}

export interface ApiResult<T> {
  data: T;
  mock: boolean; // X-Novarion-Mock: 1 → contract mock, not a model (D-006)
}

async function send<T>(path: string, init: RequestInit = {}): Promise<ApiResult<T>> {
  const response = await fetch(`/api/v1${path}`, {
    ...init,
    headers: { Accept: "application/json", ...(init.body ? { "Content-Type": "application/json" } : {}) },
  });
  const body = await response.json().catch(() => null);
  if (!response.ok) throw new ApiError(response.status, body as ErrorResponse | null);
  if (!body || typeof body !== "object" || Array.isArray(body)) {
    throw new ApiError(response.status, null); // a proxy's HTML/null response is not a successful analysis
  }
  return { data: body as T, mock: response.headers.get("X-Novarion-Mock") === "1" };
}

const get = <T>(path: string, signal?: AbortSignal) => send<T>(path, { signal });
const post = <T>(path: string, body: unknown, signal?: AbortSignal) =>
  send<T>(path, { method: "POST", body: JSON.stringify(body), signal });

export const API_SCHEMA_VERSION = "1.0.0";
// request_id is generated by the frontend per network attempt and echoed by the backend (plan §11).
export const newRequestId = () => crypto.randomUUID();

export interface CaseRequest {
  inputs: Record<string, InputValue>;
  input_revision: number;
  dataset_record_id?: number | null;
}

function pinnedBody(analysis: DisplayAnalysis, target: TargetId) {
  return {
    request_id: newRequestId(), api_schema_version: API_SCHEMA_VERSION, inputs: analysis.requestInputs ?? {},
    analysis_id: analysis.analysis_id, input_sha256: analysis.input_sha256, target,
    model_version: analysis.model_version, artifact_manifest_sha256: analysis.artifact_manifest_sha256,
  };
}

export const api = {
  ready: () => get<Schemas["HealthReady"]>("/health/ready"),
  meta: () => get<Meta>("/meta"),
  patients: () => get<Schemas["PatientListResponse"]>("/patients"),
  patient: (id: string, signal?: AbortSignal) => get<PatientBundle>(`/patients/${encodeURIComponent(id)}`, signal),
  groundTruth: (id: string) => get<Schemas["GroundTruthResponse"]>(`/patients/${encodeURIComponent(id)}/ground-truth`),
  validate: (req: CaseRequest, signal?: AbortSignal) =>
    post<ValidateResponse>("/validate", { request_id: newRequestId(), api_schema_version: API_SCHEMA_VERSION, ...req }, signal),
  predict: (req: CaseRequest, signal?: AbortSignal) =>
    post<PredictionResponse>("/predict", {
      request_id: newRequestId(), api_schema_version: API_SCHEMA_VERSION, inputs: req.inputs,
      input_revision: req.input_revision,
    }, signal),
  // Transient analyses only, pinned to the bundle that produced them (409 on any mismatch, plan §11).
  explain: (a: DisplayAnalysis, target: TargetId) => post<Schemas["ExplanationResponse"]>("/explain", pinnedBody(a, target)),
  evidence: (a: DisplayAnalysis, target: TargetId) => post<Schemas["EvidenceResponse"]>("/evidence", pinnedBody(a, target)),
};
