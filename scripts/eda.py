"""First EDA (plan §5.2-3): prevalence, label co-occurrence, near-constant binaries, distributions, associations.

Descriptive only: nothing here selects features or models (selection happens inside nested CV). Writes
results/eda.md. Usage: uv run --group train python scripts/eda.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "ml"))

from novarion_ml.data.load import build_targets, build_X, load_source
from novarion_ml.data.registry import default_registry

TARGETS = ("cad", "lad", "lcx", "rca")


def table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join([df.index.name or ""] + cols) + " |", "|" + "---|" * (len(cols) + 1)]
    for idx, row in df.iterrows():
        lines.append("| " + " | ".join([str(idx)] + [str(v) for v in row.tolist()]) + " |")
    return "\n".join(lines)


def main() -> None:
    registry = default_registry()
    source = load_source()
    X = build_X(source, registry)
    Y = pd.DataFrame(build_targets(source))
    out = ["# NOVARION — first EDA (descriptive only)", "",
           (f"Source: UCI #411, {len(X)} patients × {X.shape[1]} registry features. Generated by `scripts/eda.py`; "
            "nothing here is used for feature or model selection (that happens inside nested CV only)."), ""]

    prev = pd.DataFrame({"positives": Y.sum(), "prevalence": (Y.mean() * 100).round(1).astype(str) + " %"})
    prev.index.name = "target"
    out += ["## Prevalence", "", table(prev), "",
            ("Always-predict-positive accuracy for CAD equals its prevalence; accuracy is therefore always reported "
             "next to the baselines (plan §7)."), ""]

    combos = Y[["lad", "lcx", "rca"]].astype(str).agg("".join, axis=1).map(
        lambda s: "+".join(v for v, b in zip(("LAD", "LCX", "RCA"), s, strict=True) if b == "1") or "none")
    co = pd.crosstab(combos, Y["cad"].map({0: "CAD = Normal", 1: "CAD = CAD"}))
    co.index.name = "stenotic vessels"
    out += ["## Label co-occurrence (vessel pattern × overall CAD label)", "", table(co), "",
            "One record (row 93) has LAD = Stenotic with Cath = Normal (D-001): labels are not strictly nested.", ""]

    corr = Y.corr().round(2)
    corr.index.name = "label φ"
    out += ["## Label correlation (φ)", "", table(corr), ""]

    rows = []
    for f in registry.features:
        if f.kind == "binary":
            rate = X[f.id].mean()
            rows.append({"feature": f.id, "kind": "binary", "positive_rate": f"{rate:.1%}",
                         "flag": "constant" if rate in (0, 1) else ("rare (< 5 %)" if min(rate, 1 - rate) < 0.05 else "")})
        elif f.kind in ("ordinal", "nominal"):
            freq = X[f.id].value_counts(normalize=True)
            rows.append({"feature": f.id, "kind": f.kind,
                         "positive_rate": ", ".join(f"{k}: {v:.0%}" for k, v in freq.items()),
                         "flag": "rare category (< 5 %)" if freq.min() < 0.05 else ""})
    cat = pd.DataFrame(rows).set_index("feature")
    out += ["## Binary and categorical features", "", table(cat), ""]

    num = []
    for f in registry.features:
        if f.kind == "continuous":
            s = X[f.id].astype(float)
            num.append({"feature": f.id, "unit": f.canonical_unit, "min": s.min(), "median": s.median(),
                        "max": s.max(), "skew": round(float(s.skew()), 2), "log1p (pre-registered)": "yes" if f.log1p else ""})
    numeric = pd.DataFrame(num).set_index("feature")
    out += ["## Continuous features", "", table(numeric), ""]

    assoc = {}
    for t in TARGETS:
        scores = {}
        for f in registry.features:
            col = X[f.id]
            if f.kind in ("ordinal", "nominal"):
                col = col.map({c: i for i, c in enumerate(f.categories)}) if f.kind == "ordinal" else None
            if col is None or col.nunique() < 2:
                continue
            rho = spearmanr(col.astype(float), Y[t]).statistic
            scores[f.id] = rho
        top = sorted(scores.items(), key=lambda kv: -abs(kv[1]))[:8]
        assoc[t] = [f"{k} ({v:+.2f})" for k, v in top]
    out += ["## Strongest univariate associations (Spearman ρ with each label; descriptive, uncorrected)", ""]
    out += [f"- **{t.upper()}**: " + ", ".join(v) for t, v in assoc.items()] + [""]

    redund = []
    numeric_ids = [f.id for f in registry.features if f.kind != "nominal"]
    by_id = registry.by_id()
    enc = X[numeric_ids].apply(lambda c: c.astype(float) if pd.api.types.is_numeric_dtype(c)
                               else c.map({v: i for i, v in enumerate(by_id[c.name].categories)}).astype(float))
    m = enc.corr(method="spearman").abs()
    for i, a in enumerate(numeric_ids):
        for b in numeric_ids[i + 1:]:
            if m.loc[a, b] >= 0.7:
                redund.append(f"{a} ↔ {b} (|ρ| = {m.loc[a, b]:.2f})")
    out += ["## Highly correlated feature pairs (|ρ| ≥ 0.7)", "", *(f"- {r}" for r in redund or ["none"]), "",
            ("Weight/height vs BMI motivate the pre-registered `redundancy_reduced` feature set (D-002); the choice "
             "between feature sets is made only by inner CV."), ""]
    dup = int(X.duplicated().sum())
    out += ["## Duplicates", "", f"Exact duplicate feature rows: {dup} → CV splitting is ungrouped.", ""]
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "eda.md").write_text("\n".join(out), encoding="utf-8")
    print("results/eda.md written;", "rare/constant binaries:", int((cat["flag"] != "").sum()))



if __name__ == "__main__":
    main()
