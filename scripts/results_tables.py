"""Render Table 1 / Table 2 (plan §7) from results/metrics.json → results/tables.md.

Numbers are never typed by hand into docs: the README and report quote this generated file.
Every table carries its scope label (plan §11A "Captions"). Usage: uv run python scripts/results_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGETS = ("cad", "lad", "lcx", "rca")
T1_COLS = [("roc_auc", "ROC-AUC"), ("pr_auc", "PR-AUC"), ("accuracy", "Acc"), ("balanced_accuracy", "Bal. acc"),
           ("precision", "Precision"), ("recall", "Recall"), ("f1", "F1"), ("specificity", "Spec"), ("npv", "NPV"),
           ("brier", "Brier"), ("cal_slope", "Cal. slope"), ("cal_intercept", "Cal. intercept")]


def cell(summary: dict, key: str) -> str:
    v = summary.get(key)
    if not v or v["mean"] is None:
        return "N/A"
    sd = f" ± {v['sd']:.3f}" if v["sd"] is not None else ""
    na = f" (NA in {v['n_na']})" if v.get("n_na") else ""
    return f"{v['mean']:.3f}{sd}{na}"


def pct(x) -> str:
    return "—" if x is None else f"{100 * x:.1f}%"


def ci(x) -> str:
    return "" if not x else f" [{100 * x[0]:.1f}–{100 * x[1]:.1f}]"


def main() -> None:
    m = json.loads((ROOT / "results" / "metrics.json").read_text(encoding="utf-8"))
    out = ["# NOVARION results (generated by `scripts/results_tables.py` from `results/metrics.json`)", ""]
    out += ["## Table 1 — official metrics (Layer A) · **outer-fold mean ± SD** (25 outer folds = 5 × 5 nested CV)", ""]
    out.append("| Target | Prevalence | Model | " + " | ".join(h for _, h in T1_COLS) + " |")
    out.append("|" + "---|" * (len(T1_COLS) + 3))
    for t in TARGETS:
        r = m["targets"][t]
        rows = [("**selected (nested CV)**", r["model"])]
        rows += [(f"benchmark: {fam}", s) for fam, s in r["benchmarks"].items()]
        rows += [(f"baseline: {k.replace('_', ' ')}", s) for k, s in r["baselines"].items()]
        for name, summary in rows:
            out.append(f"| {t.upper()} | {pct(r['prevalence'])} | {name} | " +
                       " | ".join(cell(summary, k) for k, _ in T1_COLS) + " |")
    out += ["", ("Undefined metrics (e.g. precision with no predicted positives) are NA, never 0; means are over "
                 "defined folds. Benchmarks = the same selection rule restricted to one model family (descriptive "
                 "only)."), ""]

    out += ["## Table 2 — confidence tiers · **pooled OOF (prespecified repeat)**, patient-level bootstrap 95% CI", ""]
    out.append("| Target | AUC [CI] | % high-positive | PPV [CI] | % high-negative | NPV [CI] | % low confidence | "
               "Acc. on high-confidence | FN among high-neg | FP among high-pos |")
    out.append("|" + "---|" * 10)
    for t in TARGETS:
        t2 = m["targets"][t]["table2"]
        auc = "—" if t2["auc"] is None else f"{t2['auc']:.3f}" + ("" if not t2["auc_ci"] else
                                                                   f" [{t2['auc_ci'][0]:.3f}–{t2['auc_ci'][1]:.3f}]")
        out.append(f"| {t.upper()} | {auc} | {pct(t2['pct_high_positive'])} | {pct(t2['ppv'])}{ci(t2['ppv_ci'])} | "
                   f"{pct(t2['pct_high_negative'])} | {pct(t2['npv'])}{ci(t2['npv_ci'])} | "
                   f"{pct(t2['pct_low_confidence'])} | {pct(t2['accuracy_high_confidence'])} | "
                   f"{t2['fn_high_negative']} | {t2['fp_high_positive']} |")
    out += ["", ("Pre-registered confidence targets (config/targets.yaml, fixed before results; never moved, D-008): "
                 "PPV ≥ 0.90 / NPV ≥ 0.95 Wilson lower bound with n ≥ 15, on training-side OOF scores."), ""]
    out += ["## Model selection across outer folds", ""]
    for t in TARGETS:
        r = m["targets"][t]
        out.append(f"- **{t.upper()}**: families selected {r['selected_families']}; calibration-guard events "
                   f"{r['calibration_guard_events']}; folds without a high-positive region "
                   f"{r['folds_without_high_positive_region']}/25, without a high-negative region "
                   f"{r['folds_without_high_negative_region']}/25.")
    (ROOT / "results" / "tables.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("results/tables.md written")


if __name__ == "__main__":
    main()
