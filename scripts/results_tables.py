"""Render Table 1 / Table 2 (plan §7) from results/metrics.json → results/tables.md.

Numbers are never typed by hand into docs: the README and report quote this generated file.
Every table carries its scope label (plan §11A "Captions"). Usage: uv run python scripts/results_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGETS = ("cad", "lad", "lcx", "rca")
T1_COLS = [("roc_auc", "ROC-AUC"), ("pr_auc", "PR-AUC"), ("accuracy", "Acc"), ("balanced_accuracy", "Bal. acc"),
           ("precision", "Precision"), ("recall", "Recall"), ("f1", "F1"), ("specificity", "Spec"), ("npv", "NPV"),
           ("brier", "Brier"), ("cal_slope", "Cal. slope"), ("cal_intercept", "Cal. intercept")]


def cell(summary: dict, key: str) -> str:
    v = summary.get(key)
    if not v or v["mean"] is None:
        return "N/A"
    sd = f" ± {v['sd']:.3f}" if v["sd"] is not None else ""
    na = f" (NA in {v['n_na']})" if v.get("n_na") else ""
    return f"{v['mean']:.3f}{sd}{na}"


def pct(x) -> str:
    return "—" if x is None else f"{100 * x:.1f}%"


def ci(x) -> str:
    return "" if not x else f" [{100 * x[0]:.1f}–{100 * x[1]:.1f}]"


def main() -> None:
    m = json.loads((ROOT / "results" / "metrics.json").read_text(encoding="utf-8"))
    out = ["# NOVARION results (generated by `scripts/results_tables.py` from `results/metrics.json`)", ""]
    out += ["## Table 1 — official metrics (Layer A) · **outer-fold mean ± SD** (25 outer folds = 5 × 5 nested CV)", ""]
    out.append("| Target | Prevalence | Model | " + " | ".join(h for _, h in T1_COLS) + " |")
    out.append("|" + "---|" * (len(T1_COLS) + 3))
    for t in TARGETS:
        r = m["targets"][t]
        rows = [("**selected (nested CV)**", r["model"])]
        rows += [(f"benchmark: {fam}", s) for fam, s in r["benchmarks"].items()]
        rows += [(f"baseline: {k.replace('_', ' ')}", s) for k, s in r["baselines"].items()]
        for name, summary in rows:
            out.append(f"| {t.upper()} | {pct(r['prevalence'])} | {name} | " +
                       " | ".join(cell(summary, k) for k, _ in T1_COLS) + " |")
    out += ["", ("Undefined metrics (e.g. precision with no predicted positives) are NA, never 0; means are over "
                 "defined folds. Benchmarks = the same selection rule restricted to one model family (descriptive "
                 "only)."), ""]

    perm_path = ROOT / "results" / "permutation.json"
    if perm_path.exists():  # scripts/permutation_test.py (plan Tier 3)
        perm = json.loads(perm_path.read_text(encoding="utf-8"))
        out += [(f"## Table 1b — label-permutation test · {perm['permutations']} shuffles · deployed configuration, "
                "5-fold CV ROC-AUC"), "",
                ("p-value under the label-permutation null; evidence against the null under the test assumptions. "
                 "Conditional on the selected configuration (selection is not repeated under the null)."), ""]
        out.append("| Target | CV ROC-AUC | Null mean ± SD | Null max | p |")
        out.append("|" + "---|" * 5)
        for t in TARGETS:
            r = perm["targets"][t]
            out.append(f"| {t.upper()} | {r['observed_cv_auc']:.3f} | {r['null_mean']:.3f} ± {r['null_sd']:.3f} | "
                       f"{r['null_max']:.3f} | {r['p_value']:.4f} |")
        out.append("")

    out += ["## Table 2 — threshold-only confidence tiers · **pooled OOF (prespecified repeat)**, patient-level bootstrap 95% CI", "",
            ("Threshold regions are measured before the app's additional input-quality gates; these percentages do not "
             "measure displayed HIGH-confidence coverage."), ""]
    out.append("| Target | AUC [CI] | % high-positive | PPV [CI] | % high-negative | NPV [CI] | % low confidence | "
               "Acc. on high-confidence | FN among high-neg | FP among high-pos |")
    out.append("|" + "---|" * 10)
    for t in TARGETS:
        t2 = m["targets"][t]["table2"]
        auc = "—" if t2["auc"] is None else f"{t2['auc']:.3f}" + ("" if not t2["auc_ci"] else
                                                                   f" [{t2['auc_ci'][0]:.3f}–{t2['auc_ci'][1]:.3f}]")
        out.append(f"| {t.upper()} | {auc} | {pct(t2['pct_high_positive'])} | {pct(t2['ppv'])}{ci(t2['ppv_ci'])} | "
                   f"{pct(t2['pct_high_negative'])} | {pct(t2['npv'])}{ci(t2['npv_ci'])} | "
                   f"{pct(t2['pct_low_confidence'])} | {pct(t2['accuracy_high_confidence'])} | "
                   f"{t2['fn_high_negative']} | {t2['fp_high_positive']} |")
    out += ["", ("Pre-registered confidence targets (config/targets.yaml, fixed before results; never moved, D-008): "
                 "PPV ≥ 0.90 / NPV ≥ 0.95 Wilson lower bound with n ≥ 15, on training-side OOF scores."), ""]
    shown_path = ROOT / "results" / "displayed_tiers.json"
    if shown_path.exists():  # scripts/displayed_tiers.py (D-019)
        shown = json.loads(shown_path.read_text(encoding="utf-8"))
        out += [(f"## Table 2b — confidence tiers **as displayed** · served OOF analyses, model v{shown['model_version']}, "
                "patient-level bootstrap 95% CI"), "",
                ("The HIGH badge additionally requires known inputs, a typical profile and (dataset patients) a "
                 "stability interval that does not straddle the threshold, so it covers a subset of each Table 2 region."), ""]
        out.append("| Target | % HIGH-positive shown | PPV [CI] | % HIGH-negative shown | NPV [CI] | % LOW shown | "
                   "LOW reasons (count) |")
        out.append("|" + "---|" * 7)
        for t in TARGETS:
            r = shown["targets"][t]
            reasons = ", ".join(f"{k} {v}" for k, v in sorted(r["low_reasons"].items(), key=lambda x: -x[1]))
            out.append(f"| {t.upper()} | {pct(r['pct_high_positive'])} | {pct(r['ppv'])}{ci(r['ppv_ci'])} | "
                       f"{pct(r['pct_high_negative'])} | {pct(r['npv'])}{ci(r['npv_ci'])} | "
                       f"{pct(r['pct_low_confidence'])} | {reasons} |")
        out.append("")
    agreement_path = ROOT / "results" / "model_agreement.json"
    if agreement_path.exists():  # scripts/model_agreement.py (plan Tier 3 "model agreement")
        ag = json.loads(agreement_path.read_text(encoding="utf-8"))
        out += ["## Table 3b — model agreement across candidate families · **pooled OOF (prespecified repeat)**", "",
                ("For each held-out patient, LR, EBM, XGBoost and CatBoost (Table 3 benchmarks) each give a calibrated "
                 "probability and class. Descriptive robustness cue: disagreement marks patients on which the selected "
                 "model errs more often."), ""]
        out.append("| Target | All four agree on the class | Median probability range | Selected-model error when "
                   "they agree | … when they disagree |")
        out.append("|" + "---|" * 5)
        for t in TARGETS:
            r = ag["targets"][t]
            out.append(f"| {t.upper()} | {pct(r['all_four_agree'])} (n = {r['n_agree']}) | "
                       f"{r['probability_range_median']:.2f} | {pct(r['selected_error_rate_when_agree'])} | "
                       f"{pct(r['selected_error_rate_when_disagree'])} (n = {r['n_disagree']}) |")
        out.append("")
    clin_path = ROOT / "results" / "clinical_evaluation.json"
    if clin_path.exists():  # scripts/clinical_evaluation.py (D-021)
        ce = json.loads(clin_path.read_text(encoding="utf-8"))
        cb = ce["clinical_baseline"]
        out += [("## Table 6 — CAD versus the guideline pretest score · pooled OOF (prespecified repeat), "
                f"n = {cb['n']} patients with a chest-pain type"), "",
                ("Updated Diamond-Forrester pretest probability (age × sex × chest-pain type; ESC 2013, Genders 2011), "
                 "applied as published, and a logistic regression on the same three inputs refit inside the same outer "
                 f"folds. {cb['population']}. Paired patient bootstrap ({ce['bootstrap']} replicates)."), ""]
        out.append("| Comparison | AUC NOVARION | AUC comparator | ΔAUC [95% CI] | Continuous NRI [95% CI] | IDI [95% CI] |")
        out.append("|" + "---|" * 6)
        for key, label in (("novarion_vs_published_df", "vs published Diamond-Forrester"),
                           ("novarion_vs_df_inputs_refit", "vs the same 3 inputs, refit")):
            r = cb[key]
            f3 = lambda v: f"{v:+.3f}"
            out.append(f"| {label} | {r['auc_new']:.3f} | {r['auc_old']:.3f} | {f3(r['delta_auc'])} "
                       f"[{r['delta_auc_ci95'][0]:.3f}, {r['delta_auc_ci95'][1]:.3f}] | {r['nri']:+.2f} "
                       f"[{r['nri_ci95'][0]:.2f}, {r['nri_ci95'][1]:.2f}] | {f3(r['idi'])} "
                       f"[{r['idi_ci95'][0]:.3f}, {r['idi_ci95'][1]:.3f}] |")
        out += ["", "| Calibration (same patients) | Brier | Calibration-in-the-large (obs − pred) | ECE | Slope |",
                "|---|---|---|---|---|"]
        for name, label in (("novarion", "NOVARION"), ("published_df", "Published Diamond-Forrester"),
                            ("df_inputs_refit", "Same 3 inputs, refit")):
            c = cb["calibration"][name]
            out.append(f"| {label} | {c['brier']:.3f} | {c['calibration_in_the_large']:+.3f} | {c['ece']:.3f} | "
                       f"{c['calibration_slope']:.2f} |")
        out += ["", "| ESC pretest band | NOVARION: share (observed CAD) | Published D-F: share (observed CAD) |",
                "|---|---|---|"]
        for band in cb["esc_pretest_bands"]["novarion"]:
            a_, b_ = cb["esc_pretest_bands"]["novarion"][band], cb["esc_pretest_bands"]["published_df"][band]
            out.append(f"| {band} | {pct(a_['share'])} ({pct(a_['observed_cad_rate'])}) | "
                       f"{pct(b_['share'])} ({pct(b_['observed_cad_rate'])}) |")
        out += ["", ("Bands are the ESC 2013 pretest categories, shown descriptively: NOVARION does not recommend "
                     "tests or treatment."), ""]
        out += ["## Table 7 — subgroup performance · pooled OOF (prespecified repeat), patient bootstrap 95% CI", "",
                ("Descriptive only: 303 patients from one centre, so intervals are wide and no fairness claim is made. "
                 "Cells with fewer than 10 patients in either class are suppressed."), ""]
        out.append("| Target | Subgroup | n (positive) | AUC [95% CI] | Sens. | Spec. | Calibration-in-the-large |")
        out.append("|" + "---|" * 7)
        for t in TARGETS:
            for g, r in ce["subgroups"][t].items():
                if "auc" in r:
                    out.append(f"| {t.upper()} | {g} | {r['n']} ({r['n_positive']}) | {r['auc']:.3f} "
                               f"[{r['auc_ci95'][0]:.3f}, {r['auc_ci95'][1]:.3f}] | {pct(r['sensitivity'])} | "
                               f"{pct(r['specificity'])} | {r['calibration_in_the_large']:+.3f} |")
                else:
                    out.append(f"| {t.upper()} | {g} | {r['n']} ({r['n_positive']}) | {r['status']} | — | — | — |")
        dca = ce["decision_curves"]
        idx = [dca["thresholds"].index(x) for x in (0.15, 0.3, 0.5, 0.7, 0.85)]
        out += ["", "## Table 8 — decision-curve net benefit · pooled OOF (research metric, no clinical recommendation)",
                "", "| Target | Strategy | " + " | ".join(f"t = {dca['thresholds'][i]:.2f}" for i in idx) + " |",
                "|" + "---|" * (len(idx) + 2)]
        for t in TARGETS:
            for key, label in (("model", "model"), ("treat_all", "treat all")):
                out.append(f"| {t.upper()} | {label} | " + " | ".join(f"{dca[t][key][i]:+.3f}" for i in idx) + " |")
        out.append("| CAD (chest-pain patients) | published Diamond-Forrester | "
                   + " | ".join(f"{dca['cad_published_df'][i]:+.3f}" for i in idx) + " |")
        out.append("| CAD (chest-pain patients) | model | "
                   + " | ".join(f"{dca['cad_model_same_patients'][i]:+.3f}" for i in idx) + " |")
        out.append("")
    out += ["## Model selection across outer folds", ""]
    for t in TARGETS:
        r = m["targets"][t]
        out.append(f"- **{t.upper()}**: families selected {r['selected_families']}; calibration-guard events "
                   f"{r['calibration_guard_events']}; folds without a high-positive region "
                   f"{r['folds_without_high_positive_region']}/25, without a high-negative region "
                   f"{r['folds_without_high_negative_region']}/25.")
    (ROOT / "results" / "tables.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("results/tables.md written")


if __name__ == "__main__":
    main()
