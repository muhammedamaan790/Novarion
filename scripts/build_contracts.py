"""Build the frozen API contract files in contracts/ (plan §11, §11A).

  contracts/openapi.json                generated from the Pydantic schemas (never hand-edited)
  contracts/mock_reference.json         real cohort centres (median / IQR / mode / mean) + target counts
  contracts/mock_dataset_patients.json  3 dataset patients: canonical inputs, expected_input_sha256, labels
  contracts/sample_patient.json         a ready-to-send /predict request body
  contracts/mock_*.json                 one mock per response type, generated by MockService (model 0.0.0)

Deterministic: re-running produces byte-identical files (CI regenerates and fails on any diff).
Usage: uv run --group inference python scripts/build_contracts.py [--openapi-only]
"""

from __future__ import annotations

import json
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "ml"), str(ROOT / "backend")]

from app.errors import ApiError
from app.main import create_app
from app.mock import (
    CONTRACTS_DIR,
    MOCK_BUNDLE_SHA256,
    MOCK_MODEL_VERSION,
    UUID_NAMESPACE,
    MockService,
)
from app.schemas import (
    TARGET_IDS,
    AnalyzeFullRequest,
    ErrorResponse,
    EvidenceRequest,
    ExplainRequest,
    PredictRequest,
    ValidateRequest,
)
from app.service import UnavailableService
from app.settings import Settings

API_SCHEMA_VERSION = "1.0.0"


def _id(name: str) -> uuid.UUID:
    return uuid.uuid5(UUID_NAMESPACE, name)


def write_json(path: Path, obj) -> None:
    # LF on every OS (D-020): a Windows run must produce the same bytes as CI and the checkout.
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def openapi_document() -> dict:
    """Full contract (local mode = superset of the hosted build); identical regardless of mock mode."""
    return create_app(Settings(run_mode="local", mock=False), service=UnavailableService()).openapi()


def _py(value):
    return value.item() if hasattr(value, "item") else value


def build_reference_and_patients(out: Path = CONTRACTS_DIR) -> None:
    from novarion_ml.data.canonical import canonicalize_case, training_row_hashes
    from novarion_ml.data.load import build_targets, build_X, load_source, patient_id
    from novarion_ml.data.registry import default_registry

    registry = default_registry()
    source = load_source()
    X = build_X(source, registry)
    y = build_targets(source)

    features = {}
    for f in registry.features:
        col = X[f.id]
        if f.kind == "continuous":
            q1, med, q3 = (float(col.quantile(q)) for q in (0.25, 0.5, 0.75))
            features[f.id] = {"median": _py(med), "iqr": round(q3 - q1, 6)}
        elif f.kind == "binary":
            features[f.id] = {"mean": round(float(col.mean()), 6), "mode": int(col.mode().iloc[0])}
        else:
            features[f.id] = {"mode": str(col.mode().iloc[0])}
    counts = {
        t: {"negative": int((y[t] == 0).sum()), "positive": int((y[t] == 1).sum()),
            "prevalence": round(float(y[t].mean()), 6)}
        for t in TARGET_IDS
    }
    write_json(out / "mock_reference.json", {
        "note": "Real cohort statistics (full cohort) used only to centre the contract mock engine. Not a model.",
        "features": features, "target_counts": counts,
    })

    # Three illustrative records, chosen by rule (first matching row): no CAD; LAD only; three-vessel disease.
    # Rows with documented label/feature quirks (D-001 row 93, D-002 row 153) are skipped.
    labels = {t: y[t] for t in TARGET_IDS}
    rules = {
        "no_cad": lambda i: labels["cad"][i] == 0 and not any(labels[t][i] for t in ("lad", "lcx", "rca")),
        "lad_only": lambda i: labels["lad"][i] == 1 and labels["lcx"][i] == 0 and labels["rca"][i] == 0,
        "three_vessel": lambda i: all(labels[t][i] == 1 for t in ("lad", "lcx", "rca")),
    }
    hashes = training_row_hashes(X)
    patients = []
    for name, rule in rules.items():
        record = next(int(i) for i in X.index if int(i) not in (93, 153) and rule(i))
        canonical = {fid: _py(v) for fid, v in X.loc[record].items()}
        entered = {f.id: canonical[f.id] for f in registry.features if f.input_mode == "entered"}
        result = canonicalize_case(entered)
        assert result.ready and result.input_sha256 == hashes[record], f"train/serve hash mismatch for {record}"
        patients.append({
            "patient_id": patient_id(record), "dataset_record_id": record, "example": name,
            "canonical_inputs": result.canonical, "expected_input_sha256": result.input_sha256,
            "labels": {t: int(labels[t][record]) for t in TARGET_IDS},
        })
    write_json(out / "mock_dataset_patients.json", {
        "source": "Extension of Z-Alizadeh Sani (UCI #411), CC BY 4.0", "patients": patients,
    })


def build_mocks(out: Path = CONTRACTS_DIR) -> None:
    service = MockService(Settings(run_mode="live", mock=True), contracts_dir=out)
    patients = json.loads((out / "mock_dataset_patients.json").read_text(encoding="utf-8"))["patients"]
    first = patients[1]  # the LAD-only example drives the single-case mocks
    from novarion_ml.data.registry import default_registry

    entered_ids = {f.id for f in default_registry().features if f.input_mode == "entered"}
    entered = {k: v for k, v in first["canonical_inputs"].items() if k in entered_ids}
    base = {"api_schema_version": API_SCHEMA_VERSION, "inputs": entered, "unit_status": {}}
    sample = {"request_id": str(_id("sample")), "input_revision": 0, **base}
    write_json(out / "sample_patient.json", sample)

    def dump(name: str, model) -> None:
        write_json(out / f"mock_{name}.json", model.model_dump(mode="json"))

    dump("meta", service.meta())
    dump("validate", service.validate(ValidateRequest(request_id=_id("validate"), input_revision=3, **base)))
    blocked = {**entered, "age": None, "ldl": 9000, "fasting_blood_sugar": "__UNKNOWN__"}
    dump("validate_blocked", service.validate(
        ValidateRequest(request_id=_id("validate_blocked"), input_revision=4, **{**base, "inputs": blocked})))
    predict = service.predict(PredictRequest(request_id=_id("predict"), input_revision=3, **base), _id("analysis"))
    dump("predict", predict)
    unknown = {**entered, "ldl": "__UNKNOWN__"}
    dump("predict_unknown_input", service.predict(
        PredictRequest(request_id=_id("predict_unknown"), input_revision=5, **{**base, "inputs": unknown}),
        _id("analysis_unknown")))
    dump("analyze_full", service.analyze_full(
        AnalyzeFullRequest(request_id=_id("analyze_full"), **base), _id("analysis_full")))
    pinned = dict(analysis_id=_id("analysis"), input_sha256=predict.input_sha256, target="lad",
                  model_version=MOCK_MODEL_VERSION, artifact_manifest_sha256=MOCK_BUNDLE_SHA256, **base)
    dump("explain", service.explain(ExplainRequest(request_id=_id("explain"), **pinned)))
    dump("evidence", service.evidence(EvidenceRequest(request_id=_id("evidence"), **pinned)))
    dump("patients", service.patients())
    dump("patient", service.patient(first["patient_id"]))
    dump("ground_truth", service.ground_truth(first["patient_id"]))
    dump("evaluation", service.evaluation())
    dump("global_importance", service.global_importance("lad"))
    dump("models", service.models())
    dump("model_report", service.model_report("0.1.0"))
    dump("error", ErrorResponse(
        error_code="TARGET_FAILED", message="One or more targets failed; nothing was committed.",
        request_id=_id("error"), commit_status="rejected", prediction_status="unavailable",
        target_status={"cad": "computed_not_committed", "lad": "computed_not_committed",
                       "lcx": "computed_not_committed", "rca": "error"},
        details={"failed_targets": ["rca"]},
    ))
    try:
        service.explain(ExplainRequest(request_id=_id("error_artifact"), **{**pinned, "model_version": "1.0.0"}))
    except ApiError as exc:
        dump("error_artifact_mismatch", exc.body)


def build_all(out: Path = CONTRACTS_DIR, openapi_only: bool = False) -> None:
    out.mkdir(exist_ok=True)
    write_json(out / "openapi.json", openapi_document())
    if not openapi_only:
        build_reference_and_patients(out)
        build_mocks(out)


def main() -> None:
    build_all(openapi_only="--openapi-only" in sys.argv)
    print(f"contracts written to {CONTRACTS_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
