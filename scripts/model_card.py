"""Generate docs/model_card.md from the bundle manifest, results/metrics.json and results/ablation.json.

Numbers are never typed by hand: re-run after any retraining. Usage: uv run python scripts/model_card.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGETS = ("cad", "lad", "lcx", "rca")
NAMES = {"cad": "Overall CAD (Cath)", "lad": "LAD stenosis", "lcx": "LCX stenosis", "rca": "RCA stenosis"}
GROUPS = ("demographics", "history", "symptoms_exam", "ecg", "labs", "echo")


def ms(summary: dict, key: str) -> str:
    v = summary.get(key) or {}
    if v.get("mean") is None:
        return "N/A"
    return f"{v['mean']:.3f} ± {v['sd']:.3f}" if v.get("sd") is not None else f"{v['mean']:.3f}"


def pct(x) -> str:
    return "—" if x is None else f"{100 * x:.1f}%"


def main() -> None:
    reg = json.loads((ROOT / "registry" / "models.json").read_text(encoding="utf-8"))
    entry = next(m for m in reg["models"] if m["version"] == reg["production_version"])
    manifest = json.loads((ROOT / entry["path"] / "manifest.json").read_text(encoding="utf-8"))["manifest"]
    metrics = json.loads((ROOT / "results" / "metrics.json").read_text(encoding="utf-8"))
    ablation_path = ROOT / "results" / "ablation.json"
    ablation = json.loads(ablation_path.read_text(encoding="utf-8")) if ablation_path.exists() else None

    md = [f"# NOVARION model card — v{manifest['model_version']}", "",
          "> Decision support / educational purposes only. Not a substitute for formal diagnostic imaging.", "",
          "*Generated by `scripts/model_card.py` from the bundle manifest and `results/` — do not edit by hand.*", "",
          "## Model details", "",
          (f"- **Version:** {manifest['model_version']} (preprocessing {manifest['preprocessing_version']}); "
          f"artifact manifest `{entry['artifact_manifest_sha256'][:16]}…`; created {manifest['created_at']}."),
          "- **Four independent binary classifiers**, one per target (probabilities are not constrained to nest):", ""]
    md += ["| Target | Deployed configuration (selected by inner CV on all 303, 1-SE rule) |", "|---|---|"]
    for t in TARGETS:
        md.append(f"| {NAMES[t]} | `{manifest['selected'][t]}` |")
    md += ["",
           "- **Calibration:** Platt scaling on cross-fitted out-of-fold logits (slope guard a > 0).",
           ("- **Operating threshold (Layer A):** Youden's J on calibrated training-side OOF probabilities; every case "
           "always receives a binary prediction."),
           ("- **Model confidence (Layer B):** HIGH only inside a region whose Wilson-95% lower bound met the "
           "pre-registered PPV ≥ 0.90 / NPV ≥ 0.95 (n ≥ 15) on training-side OOF scores; forced LOW for UNKNOWN inputs "
           "or an atypical profile."),
           ("- **Explanations:** exactly additive contributions in calibrated log-odds (LR: linear SHAP; XGBoost/"
           "CatBoost: TreeSHAP; EBM: native terms), aggregated to registry features; additivity is tested."),
           ("- **Stability (dataset patients only):** 10th–90th percentile of 100 refit-bootstrap replicates of the fold "
           "model (outer-training rows only, threshold fixed); an interval straddling the threshold forces LOW with "
           "reason \"unstable\" (D-017). New cases have no interval."),
           ("- **Updates:** governed learning loop (D-018): verified outcomes only, forward holdout, pre-registered "
           "paired gate, human-approved promotion, hash-chained audit log. v1.0.1 serves the frozen v1.0.0 models "
           "unchanged; no learning-loop update has been promoted."),
           "- **Libraries:** " + ", ".join(f"{k} {v}" for k, v in manifest["libraries"].items()) + ".", "",
           "## Intended use", "",
           ("Educational and research decision support: estimating the probability of the dataset's CAD and ≥50% "
           "LAD/LCX/RCA stenosis labels from routine clinical features, visualized on a reference 3D heart, for review by "
           "clinicians or clinical/research reviewers."), "",
           "## Out of scope", "",
           ("Diagnosis; lesion location or severity (each vessel is tinted as a whole); test or treatment "
           "recommendations; causal interpretation of contributions; event or mortality risk; patient self-assessment; "
           "any population other than the source cohort without external validation."), "",
           "## Data", "",
           ("Extension of Z-Alizadeh Sani dataset (UCI #411, CC BY 4.0): 303 patients, 55 predictors (demographic, "
           "history, examination, ECG, laboratory, echocardiography), labels Cath (overall CAD), LAD, LCX, RCA. "
           "Labels and their derivatives are never model inputs (leakage denylist, tested). "
           f"Training-matrix hash `{manifest['training_data_sha256'][:16]}…`; source file hash "
           f"`{manifest['source_data_sha256'][:16]}…`."), "",
           "## Evaluation (internal validation only)", "",
           ("Nested cross-validation: outer stratified 5-fold × 5 repeats, inner 5-fold for model selection; thresholds and "
           "calibration chosen on training-side data only. **Table scope: outer-fold mean ± SD (25 folds).**"), "",
           ("| Target | Prevalence | ROC-AUC | Balanced acc. | Sensitivity | Specificity | Brier | Cal. slope | "
           "Always-positive accuracy |"), "|---|---|---|---|---|---|---|---|---|"]
    for t in TARGETS:
        r = metrics["targets"][t]
        m = r["model"]
        md.append(f"| {NAMES[t]} | {pct(r['prevalence'])} | {ms(m, 'roc_auc')} | {ms(m, 'balanced_accuracy')} | "
                  f"{ms(m, 'recall')} | {ms(m, 'specificity')} | {ms(m, 'brier')} | {ms(m, 'cal_slope')} | "
                  f"{ms(r['baselines']['always_positive'], 'accuracy')} |")
    md += ["", "**Confidence tiers — scope: pooled OOF (prespecified repeat), bootstrap 95% CI.**", "",
           "| Target | HIGH-positive share | PPV [CI] | HIGH-negative share | NPV [CI] | LOW share |",
           "|---|---|---|---|---|---|"]
    for t in TARGETS:
        t2 = metrics["targets"][t]["table2"]
        ci = (lambda c: f" [{pct(c[0])}–{pct(c[1])}]" if c else "")
        md.append(f"| {NAMES[t]} | {pct(t2['pct_high_positive'])} | {pct(t2['ppv'])}{ci(t2['ppv_ci'])} | "
                  f"{pct(t2['pct_high_negative'])} | {pct(t2['npv'])}{ci(t2['npv_ci'])} | {pct(t2['pct_low_confidence'])} |")
    md += ["", ("No vessel model qualified a high-confidence region at the pre-registered targets; the targets were "
           "fixed before results and are not lowered (D-008). Every case still receives a binary prediction."), ""]
    if ablation:
        md += ["## Feature-group ablation (descriptive)", "",
               f"Scope: {ablation['scope']}. Metric: {ablation['metric']}.", "",
               "| Target | Full | " + " | ".join(f"− {g}" for g in GROUPS) + " |", "|---|---|" + "---|" * len(GROUPS)]
        for t in TARGETS:
            a = ablation["targets"][t]
            md.append(f"| {NAMES[t]} | {a['full']['mean']:.3f} | " +
                      " | ".join(f"{a[f'without_{g}']['delta_mean']:+.3f}" for g in GROUPS) + " |")
        md.append("")
    md += ["## Limitations", "",
           ("- Single public cohort of 303 patients (high CAD prevalence, 71%); PPV/NPV do not transfer to populations "
           "with different prevalence."),
           "- Internal validation only; no external or temporal validation.",
           "- One discordant label record (D-001: LAD stenotic with Cath = Normal) is kept as published.",
           "- Contributions are associations learned by the model, not causes; correlated features share credit.",
           "- The 3D anatomy is a reference model (BodyParts3D), not a patient-specific reconstruction.", "",
           "## Ethical considerations", "",
           ("Human-in-the-loop by design: a review note records that a person examined the basis of an output; there is no "
           "accept-diagnosis action. The hosted demo is for de-identified or synthetic data only; cases are stored only "
           "in the user's browser and the server keeps nothing."), ""]
    (ROOT / "docs" / "model_card.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("docs/model_card.md written")


if __name__ == "__main__":
    main()
